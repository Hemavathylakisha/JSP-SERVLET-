package com.OnlineShoppingCart;

public class Tracking {

    private String id;
    private String status;

    public Tracking() {}

	public String getId() {
		return id;
	}

	public void setId(String id) {
		this.id = id;
	}

	public String getStatus() {
		return status;
	}

	public void setStatus(String status) {
		this.status = status;
	}

    
}
